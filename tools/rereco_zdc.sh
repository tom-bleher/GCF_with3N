#!/bin/bash
# Re-reconstruct only the ZDC of an existing run_eic_sim.sh run with the current ZDC clustering flags (#212):
#   tools/rereco_zdc.sh RUN_DIR [JOBS]
# For every sim_NNNN.edm4hep.root it runs eicrecon with the run's production flags (reco_flags.txt) plus the ZDC
# flags of run_eic_sim.sh, writing only the ZDC cluster associations and neutrals to zdc_NNNN.edm4eic.root
# (about 1 min and 0.35 MB per 1000 events; JANA runs only the factories those collections need). extract in
# tools/eic_src_analysis.py then takes the ZDC from these side files; the reco files are left as they are.
# zdc_reco.json records the flags, the EICrecon build and the chunks. Run on the host; it enters eic-shell.
set -uo pipefail
RUN=$(cd "${1:?usage: rereco_zdc.sh RUN_DIR [JOBS]}" && pwd); JOBS=${2:-32}
GCF=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
: "${EIC_SHELL:=$HOME/eic/eic-shell}" "${FIELDMAPS:=$HOME/eic/fieldmaps}"
[[ -f $RUN/run.json && -f $RUN/geometry.xml && -d $RUN/prefetch/calibrations ]] || { echo "rereco_zdc: $RUN is not a finished run" >&2; exit 2; }
read -r EPIC CONFIG EICRECON < <(python3 -c "
import json; j = json.load(open('$RUN/run.json')); print(j['epic']['install'], j['epic']['config'], j['eicrecon']['install'])")
mapfile -t ZDC < <(grep -o -- '-PZDC:[^ ]*' "$GCF/tools/run_eic_sim.sh")
[[ ${#ZDC[@]} -gt 0 ]] || { echo "rereco_zdc: no ZDC flags in run_eic_sim.sh" >&2; exit 2; }
mapfile -t FLAGS < <(python3 -c "
import json; print('\n'.join(json.load(open('$RUN/run.json'))['eicrecon']['flags']))" | grep -v -- '-PZDC:')
COLS=EventHeader,HcalFarForwardZDCClusterAssociations,EcalFarForwardZDCClusterAssociations,ReconstructedHcalFarForwardZDCNeutrals
cat > "$RUN/zdc_stage.sh" <<IN
#!/bin/bash
# generated by tools/rereco_zdc.sh; runs inside eic-shell
set -uo pipefail
cd "$RUN"
source "$EPIC/bin/thisepic.sh" "$CONFIG"
source "$EICRECON/bin/eicrecon-this.sh"
export DETECTOR_CACHE="$RUN/prefetch/calibrations"
one() {
  local i=\$1 w="$RUN/zdcwork_\$1"
  mkdir -p "\$w" && cd "\$w" && ln -sfn "$FIELDMAPS" fieldmaps
  if eicrecon ../sim_\$i.edm4hep.root -Pnthreads=1 -Pdd4hep:xml_files=../geometry.xml ${FLAGS[*]} ${ZDC[*]} \\
       -Ppodio:output_collections=$COLS -Ppodio:output_file=zdc_tmp.edm4eic.root > ../zdc_\$i.log 2>&1; then
    mv zdc_tmp.edm4eic.root ../zdc_\$i.edm4eic.root && echo 0 > ../exit_zdc_\$i
  else echo 1 > ../exit_zdc_\$i; fi
  cd .. && rm -rf "\$w"
}
for f in sim_*.edm4hep.root; do
  i=\${f#sim_}; i=\${i%%.*}
  [[ -f zdc_\$i.edm4eic.root && \$(cat exit_zdc_\$i 2>/dev/null) == 0 ]] && continue
  while [ "\$(jobs -rp | wc -l)" -ge $JOBS ]; do wait -n || true; done
  one "\$i" &
done
wait
IN
printf '%s\n' "bash $RUN/zdc_stage.sh" | "$EIC_SHELL" > "$RUN/zdc_stage.log" 2>&1 || true
ok=$(grep -lxF 0 "$RUN"/exit_zdc_* 2>/dev/null | wc -l); bad=$(grep -lxF 1 "$RUN"/exit_zdc_* 2>/dev/null | wc -l)
python3 - "$RUN" "$EICRECON" "$ok" "$bad" "${ZDC[@]}" <<'PY'
import json, subprocess, sys
from datetime import datetime, timezone
run, eicrecon, ok, bad, *flags = sys.argv[1:]
src = eicrecon.rsplit("/install", 1)[0]
commit = subprocess.run(["git", "-C", src, "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip() or None
json.dump({"created": datetime.now(timezone.utc).isoformat(timespec="seconds"), "eicrecon": {"install": eicrecon, "commit": commit},
           "zdc_flags": flags, "chunks_ok": int(ok), "chunks_failed": int(bad),
           "note": "ZDC-only re-reconstruction (tools/rereco_zdc.sh, #212); extract reads the ZDC from zdc_NNNN.edm4eic.root"},
          open(f"{run}/zdc_reco.json", "w"), indent=2)
PY
echo "rereco_zdc: $RUN: $ok chunks ok, $bad failed"
